r"""Put the luci3D logo and "luci3d HARDWARE" on the board's back silkscreen as one footprint.

Run with KiCad's Python:
    "C:\Program Files\KiCad\10.0\bin\python.exe" place_logo.py board.kicad_pcb logo.json

The footprint (LOGO1) is board-only, so it stays out of the schematic, the BOM and the
placement file. Drag it around in KiCad like any part; running this again replaces it.
It is also written to lib/open-dvr.pretty/luci3d_logo.kicad_mod, for use on other boards.
"""
import json
import os
import sys

import pcbnew

OX, OY = 100.0, 100.0
X, Y = 14.0, 22.0          # logo centre, board coordinates (mm)
TEXT = 'luci3d HARDWARE'
TEXT_SIZE, TEXT_THICK = 1.3, 0.2
TEXT_GAP = 1.4             # mm between the logo and the text
LIB = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', 'lib', 'open-dvr.pretty')


def pt(x, y):
    return pcbnew.VECTOR2I(pcbnew.FromMM(x), pcbnew.FromMM(y))


def text_y(d):
    return d['height_mm'] / 2 + TEXT_GAP + TEXT_SIZE / 2


def polygons(d):
    """The logo as fractured polygons (outlines with the holes cut in)."""
    ps = pcbnew.SHAPE_POLY_SET()
    for o in d['outer']:
        ps.NewOutline()
        for x, y in o:
            ps.Append(pcbnew.FromMM(x), pcbnew.FromMM(y))
    hs = pcbnew.SHAPE_POLY_SET()
    for h in d['holes']:
        hs.NewOutline()
        for x, y in h:
            hs.Append(pcbnew.FromMM(x), pcbnew.FromMM(y))
    ps.BooleanSubtract(hs)
    ps.Fracture()
    return ps


def build(b, ps, d):
    fp = pcbnew.FOOTPRINT(b)
    fp.SetFPID(pcbnew.LIB_ID('open-dvr', 'luci3d_logo'))
    fp.SetReference('LOGO1')
    fp.SetValue('luci3d_logo')
    for f in (fp.Reference(), fp.Value()):
        f.SetVisible(False)
        f.SetLayer(pcbnew.F_Fab)
    fp.SetBoardOnly(True)
    fp.SetExcludedFromBOM(True)
    fp.SetExcludedFromPosFiles(True)
    for i in range(ps.OutlineCount()):
        one = pcbnew.SHAPE_POLY_SET()
        one.AddOutline(ps.Outline(i))
        s = pcbnew.PCB_SHAPE(fp, pcbnew.SHAPE_T_POLY)
        s.SetPolyShape(one)
        s.SetFilled(True)
        s.SetWidth(0)
        s.SetLayer(pcbnew.F_SilkS)
        fp.Add(s)
    t = pcbnew.PCB_TEXT(fp)
    t.SetText(TEXT)
    t.SetLayer(pcbnew.F_SilkS)
    t.SetTextSize(pt(TEXT_SIZE, TEXT_SIZE))
    t.SetTextThickness(pcbnew.FromMM(TEXT_THICK))
    t.SetPosition(pt(0, text_y(d)))
    fp.Add(t)
    return fp


def write_lib(ps, d):
    """The same footprint, unflipped, as a library file. KiCad's Python has no working
    FootprintSave here, so the file is written as text."""
    T = pcbnew.ToMM
    font = '(effects (font (size %g %g) (thickness %g)))'
    out = ['(footprint "luci3d_logo"', '(version 20260206)', '(generator "open-dvr")', '(layer "F.Cu")',
           '(descr "luci3D logo and text, generated by tools/logo/place_logo.py from art/luci3d-logo.png")',
           '(attr board_only exclude_from_pos_files exclude_from_bom)']
    for name, val in (('Reference', 'LOGO1'), ('Value', 'luci3d_logo')):
        out.append('(property "%s" "%s" (at 0 0 0) (layer "F.Fab") (hide yes) %s)' % (name, val, font % (1, 1, 0.15)))
    for i in range(ps.OutlineCount()):
        ol = ps.Outline(i)
        xy = ' '.join('(xy %g %g)' % (round(T(ol.CPoint(k).x), 4), round(T(ol.CPoint(k).y), 4))
                      for k in range(ol.PointCount()))
        out.append('(fp_poly (pts %s) (stroke (width 0) (type solid)) (fill yes) (layer "F.SilkS"))' % xy)
    out.append('(fp_text user "%s" (at 0 %g 0) (layer "F.SilkS") %s)' % (
        TEXT, text_y(d), font % (TEXT_SIZE, TEXT_SIZE, TEXT_THICK)))
    body = out[0] + '\n' + ''.join('\t' + line + '\n' for line in out[1:]) + ')\n'
    os.makedirs(LIB, exist_ok=True)
    with open(os.path.join(LIB, 'luci3d_logo.kicad_mod'), 'w', encoding='utf-8', newline='\n') as f:
        f.write(body)


def main(pcb, logo):
    d = json.load(open(logo))
    ps = polygons(d)
    write_lib(ps, d)
    b = pcbnew.LoadBoard(pcb)
    old = [f for f in b.GetFootprints() if f.GetReference() == 'LOGO1']
    fp = build(b, ps, d)
    for f in old:
        b.Remove(f)
    b.Add(fp)
    fp.SetPosition(pt(OX + X, OY + Y))
    fp.Flip(fp.GetPosition(), pcbnew.FLIP_DIRECTION_LEFT_RIGHT)     # to the back, mirrored
    pcbnew.SaveBoard(pcb, b)
    print('LOGO1 on the back at (%.1f, %.1f): %d polygons + "%s"%s; library copy in lib/open-dvr.pretty' % (
        X, Y, ps.OutlineCount(), TEXT, ' (replaced the old one)' if old else ''))


if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
